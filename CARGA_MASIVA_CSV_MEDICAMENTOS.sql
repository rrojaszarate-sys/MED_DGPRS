    VALUES ('Distribuidora Farmacéutica Nacional', 'DFN850101ABC', '555-1234', 30, true)
    RETURNING id INTO v_supplier_id;
  END IF;

  SELECT id INTO v_contract_id FROM contracts WHERE codigo_contrato = 'CA-0158-2025';
  IF v_contract_id IS NULL THEN
    INSERT INTO contracts (codigo_contrato, supplier_id, fecha_inicio, fecha_fin, monto_total, estado)
    VALUES ('CA-0158-2025', v_supplier_id, '2025-01-01', '2025-12-31', 8500000.00, 'activo')
    ON CONFLICT (codigo_contrato) DO NOTHING
    RETURNING id INTO v_contract_id;
    IF v_contract_id IS NULL THEN
      SELECT id INTO v_contract_id FROM contracts WHERE codigo_contrato = 'CA-0158-2025';
    END IF;
  END IF;

  RAISE NOTICE '✅ Centro: %', v_center_name;
  RAISE NOTICE '✅ Procesando lotes...';
  RAISE NOTICE '';

  -- Procesar cada fila del CSV
  FOR v_row IN SELECT * FROM temp_csv_medicamentos ORDER BY clave, lote LOOP

    -- Convertir fecha de caducidad
    -- Formatos: "ENE 2026", "AGO 26", "ene-28", "SEP 26", etc.
    BEGIN
      v_mes := UPPER(split_part(v_row.fecha_cad, ' ', 1));
      v_mes := UPPER(split_part(v_mes, '-', 1));
      v_anio := split_part(v_row.fecha_cad, ' ', 2);
      IF v_anio = '' THEN
        v_anio := split_part(v_row.fecha_cad, '-', 2);
      END IF;

      -- Convertir mes a número
      v_mes := CASE
        WHEN v_mes = 'ENE' THEN '01'
        WHEN v_mes = 'FEB' THEN '02'
        WHEN v_mes = 'MAR' THEN '03'
        WHEN v_mes = 'ABR' THEN '04'
        WHEN v_mes = 'MAY' THEN '05'
        WHEN v_mes = 'JUN' THEN '06'
        WHEN v_mes = 'JUL' THEN '07'
        WHEN v_mes = 'AGO' THEN '08'
        WHEN v_mes = 'SEP' THEN '09'
        WHEN v_mes = 'OCT' THEN '10'
        WHEN v_mes = 'NOV' THEN '11'
        WHEN v_mes = 'DIC' THEN '12'
        ELSE '12'
      END;

      -- Convertir año (26 → 2026, 28 → 2028)
      IF length(v_anio) = 2 THEN
        v_anio := '20' || v_anio;
      END IF;

      v_fecha_cad_calculada := (v_anio || '-' || v_mes || '-28')::DATE;

    EXCEPTION
      WHEN OTHERS THEN
        v_fecha_cad_calculada := current_date + interval '2 years';
    END;

    -- Crear entrada en medication_catalog (si no existe)
    INSERT INTO medication_catalog (
      codigo_medicamento,
      nombre_generico,
      nombre_comercial,
      forma_farmaceutica,
      via_administracion,
      categoria,
      requiere_receta,
      controlado,
      temperatura_almacenamiento,
      is_active
    ) VALUES (
      v_row.clave,
      substring(v_row.descripcion, 1, 200),
      v_row.marca,
      'Tableta',  -- Por defecto
      'Oral',
      'General',
      false,
      false,
      '15-25°C',
      true
    )
    ON CONFLICT (codigo_medicamento) DO UPDATE
      SET nombre_comercial = COALESCE(medication_catalog.nombre_comercial, '') || ', ' || EXCLUDED.nombre_comercial,
          updated_at = now()
    RETURNING id INTO v_catalog_id;

    IF v_catalog_id IS NULL THEN
      SELECT id INTO v_catalog_id FROM medication_catalog WHERE codigo_medicamento = v_row.clave;
    END IF;

    -- Crear instancia en medications (si no existe)
    SELECT id INTO v_medication_id
    FROM medications
    WHERE center_id = v_center_id AND catalog_id = v_catalog_id;

    IF v_medication_id IS NULL THEN
      INSERT INTO medications (
        center_id,
        catalog_id,
        nombre,
        unidad_medida,
        categoria,
        requiere_refrigeracion,
        is_active
      ) VALUES (
        v_center_id,
        v_catalog_id,
        substring(v_row.descripcion, 1, 200),
        v_row.unidad,
        'General',
        false,
        true
      )
      RETURNING id INTO v_medication_id;

      v_count_meds := v_count_meds + 1;
    END IF;

    -- Crear lote
    INSERT INTO batches (
      medication_id,
      center_id,
      supplier_id,
      numero_lote,
      cantidad_inicial,
      cantidad_actual,
      fecha_fabricacion,
      fecha_caducidad,
      fecha_ingreso,
      stock_minimo,
      stock_maximo,
      estado,
      observaciones
    ) VALUES (
      v_medication_id,
      v_center_id,
      v_supplier_id,
      v_row.lote,
      v_row.inventario,
      v_row.inventario,
      v_fecha_cad_calculada - interval '18 months',  -- Fabricación estimada
      v_fecha_cad_calculada,
      v_fecha_cad_calculada - interval '12 months',  -- Ingreso estimado
      GREATEST(v_row.inventario / 10, 50),
      v_row.inventario * 2,
      'disponible',
      'Marca: ' || v_row.marca || ' - Contrato: ' || v_row.contrato
    );

    v_count_lotes := v_count_lotes + 1;

    IF v_count_lotes % 20 = 0 THEN
      RAISE NOTICE '  → Procesados % lotes...', v_count_lotes;
    END IF;

  END LOOP;

  RAISE NOTICE '';
  RAISE NOTICE '====================================';
  RAISE NOTICE '✅ COMPLETADO';
  RAISE NOTICE 'Medicamentos únicos: %', v_count_meds;
  RAISE NOTICE 'Lotes totales: %', v_count_lotes;
  RAISE NOTICE 'Stock total: % unidades', (SELECT sum(inventario) FROM temp_csv_medicamentos);
  RAISE NOTICE '====================================';

END $$;

